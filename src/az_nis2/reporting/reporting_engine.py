from __future__ import annotations

from datetime import datetime
from io import BytesIO
from pathlib import Path
from typing import Any

import matplotlib.pyplot as plt
from matplotlib.patches import Wedge
from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import (
    Image,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)


class ReportingEngine:
    def generate_pdf(
        self,
        inventory: list[dict],
        findings: list[dict],
        compliance: dict,
        risk: dict,
        output_path: str | Path,
    ) -> None:
        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)

        styles = self._build_styles()

        doc = SimpleDocTemplate(
            str(output_path),
            pagesize=A4,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36,
            title="Azure NIS2 Security Assessment Report",
        )

        story = []

        story.extend(self._build_title_page(styles))
        story.append(PageBreak())

        story.extend(self._build_executive_summary(
            inventory,
            findings,
            compliance,
            risk,
            styles,
        ))
        story.append(PageBreak())

        story.extend(self._build_detailed_findings(findings, styles))
        story.append(PageBreak())

        story.extend(self._build_compliance_summary(compliance, styles))
        story.append(PageBreak())

        story.extend(self._build_resource_risk_summary(risk, styles))

        doc.build(story)

    def _build_title_page(self, styles: dict) -> list:
        return [
            Paragraph("Cloud Infrastructure Security Assessment Framework", styles["TitleCustom"]),
            Spacer(1, 18),
            Paragraph("Microsoft Azure - NIS2 Security Assessment Report", styles["Heading1Custom"]),
            Spacer(1, 24),
            Paragraph(
                "Report generated by the Azure NIS2 Security Assessment Framework.",
                styles["Normal"],
            ),
            Spacer(1, 8),
            Paragraph(
                f"Generated at: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
                styles["Small"],
            ),
            Spacer(1, 24),
            Paragraph(
                "The report summarizes discovered Azure resources, detected security "
                "misconfigurations, NIS2 compliance status, and environment risk score.",
                styles["Normal"],
            ),
        ]

    def _build_executive_summary(
        self,
        inventory: list[dict],
        findings: list[dict],
        compliance: dict,
        risk: dict,
        styles: dict,
    ) -> list:
        story = [
            Paragraph("1. Executive Summary", styles["Heading1Custom"]),
            Paragraph(
                "This section provides a high-level view of the assessed Azure environment.",
                styles["Normal"],
            ),
            Spacer(1, 12),
        ]

        overall = risk.get("overall", {})
        compliance_summary = compliance.get("summary", {})

        summary_data = [
            ["Metric", "Value"],
            ["Discovered Azure resources", str(overall.get("discovered_resources", len(inventory)))],
            ["Assessed Azure resources", str(overall.get("assessed_resources", 0))],
            ["Unassessed Azure resources", str(overall.get("unassessed_resources", 0))],
            ["Total findings", str(len(findings))],
            ["Risk grade", overall.get("risk_grade", "N/A")],
            ["Risk score", f"{overall.get('score_percent', 0)}%"],
            ["Base score", f"{overall.get('base_score_percent', 0)}%"],
            ["NIS2 passed controls", str(compliance_summary.get("passed_controls", 0))],
            ["NIS2 failed controls", str(compliance_summary.get("failed_controls", 0))],
            ["NIS2 compliance", f"{compliance_summary.get('compliance_percentage', 0)}%"],
        ]

        story.append(Spacer(1, 8))
        story.append(Paragraph(
            "Risk score methodology: discovered resources include all Azure resources found in the target Resource Group. "
            "Assessed resources are the subset for which the framework collected configuration data and applied security rules. "
            "Unassessed resources remain visible in the inventory but are excluded from the risk denominator.",
            styles["BodyText"],
        ))
        story.append(Spacer(1, 12))

        story.append(self._make_table(summary_data, [220, 260]))
        story.append(Spacer(1, 16))

        gauge = self._make_risk_gauge(
            score_percent=overall.get("score_percent", 0),
            grade=overall.get("risk_grade", "N/A"),
        )

        if gauge:
            story.append(Image(gauge, width=260, height=145))
            story.append(Spacer(1, 12))

        severity_chart = self._make_severity_chart(risk.get("by_severity", {}))

        if severity_chart:
            story.append(Image(severity_chart, width=360, height=190))
            story.append(Spacer(1, 12))

        story.append(Paragraph("Resource Inventory", styles["Heading2Custom"]))

        inventory_data = [["Name", "Type", "Location"]]

        for resource in inventory:
            inventory_data.append([
                resource.get("name", ""),
                self._shorten(resource.get("type", ""), 42),
                resource.get("location", "") or "-",
            ])

        story.append(self._make_table(inventory_data, [130, 270, 80]))

        return story

    def _build_detailed_findings(self, findings: list[dict], styles: dict) -> list:
        story = [
            Paragraph("2. Detailed Findings", styles["Heading1Custom"]),
            Paragraph(
                "This section lists the security misconfigurations detected by the Configuration Analyzer.",
                styles["Normal"],
            ),
            Spacer(1, 12),
        ]

        if not findings:
            story.append(Paragraph("No security findings detected.", styles["Normal"]))
            return story

        severity_order = {
            "Critical": 0,
            "High": 1,
            "Medium": 2,
            "Low": 3,
        }

        sorted_findings = sorted(
            findings,
            key=lambda item: severity_order.get(item.get("severity", ""), 99),
        )

        for idx, finding in enumerate(sorted_findings, start=1):
            resource = finding.get("resource", {})
            evidence = finding.get("evidence", {})

            story.append(Paragraph(
                f"{idx}. {finding.get('title', 'Finding')}",
                styles["Heading2Custom"],
            ))

            finding_data = [
                ["Severity", finding.get("severity", "N/A")],
                ["Rule ID", finding.get("rule_id", "N/A")],
                ["Resource", resource.get("name", "N/A")],
                ["Resource type", resource.get("type", "N/A")],
                ["Message", finding.get("message", "")],
                ["Description", finding.get("description", "")],
                ["Rationale", finding.get("rationale", "")],
                ["Remediation", finding.get("remediation", "")],
                ["NIS2 controls", ", ".join(finding.get("nis2_controls", []))],
                ["References", self._format_references(finding.get("references", []))],
                ["Evidence", self._format_evidence(evidence)],
            ]

            story.append(self._make_table(finding_data, [110, 370]))
            story.append(Spacer(1, 12))

        return story

    def _build_compliance_summary(self, compliance: dict, styles: dict) -> list:
        story = [
            Paragraph("3. NIS2 Compliance Summary", styles["Heading1Custom"]),
            Paragraph(
                "This section maps detected Azure misconfigurations to NIS2 Article 21 controls. "
                "The mapping is technical and interpretative, not an official NIS2 checklist.",
                styles["Normal"],
            ),
            Spacer(1, 12),
        ]

        summary = compliance.get("summary", {})

        summary_data = [
            ["Metric", "Value"],
            ["Framework", compliance.get("framework", "NIS2")],
            ["Version", compliance.get("version", "N/A")],
            ["Total controls", str(summary.get("total_controls", 0))],
            ["Passed controls", str(summary.get("passed_controls", 0))],
            ["Failed controls", str(summary.get("failed_controls", 0))],
            ["Compliance percentage", f"{summary.get('compliance_percentage', 0)}%"],
        ]

        story.append(self._make_table(summary_data, [160, 320]))
        story.append(Spacer(1, 16))

        controls_data = [["Control", "Status", "Findings", "Title"]]

        for control in compliance.get("controls", []):
            controls_data.append([
                control.get("control_id", ""),
                control.get("status", ""),
                str(control.get("findings_count", 0)),
                self._shorten(control.get("title", ""), 48),
            ])

        story.append(self._make_table(controls_data, [95, 60, 55, 270]))
        story.append(Spacer(1, 16))

        for control in compliance.get("controls", []):
            story.append(Paragraph(
                f"{control.get('control_id')} - {control.get('status')}",
                styles["Heading2Custom"],
            ))

            control_data = [
                ["Title", control.get("title", "")],
                ["Description", control.get("description", "")],
                ["Mapped rules", ", ".join(control.get("mapped_rules", []))],
                ["Violated rules", ", ".join(control.get("violated_rules", [])) or "-"],
                ["Affected resources", self._format_affected_resources(control.get("affected_resources", []))],
                ["Remediation", control.get("remediation", "")],
            ]

            story.append(self._make_table(control_data, [120, 360]))
            story.append(Spacer(1, 12))

        return story

    def _build_resource_risk_summary(self, risk: dict, styles: dict) -> list:
        story = [
            Paragraph("4. Resource Risk Summary", styles["Heading1Custom"]),
            Paragraph(
                "This section ranks Azure resources by their calculated risk score.",
                styles["Normal"],
            ),
            Spacer(1, 12),
        ]

        resources = risk.get("resources", [])

        if not resources:
            story.append(Paragraph("No resources available for risk scoring.", styles["Normal"]))
            return story

        data = [["Resource", "Type", "Findings", "Risk %", "Sensitivity"]]

        for resource in resources:
            data.append([
                resource.get("resource_name", ""),
                self._shorten(resource.get("resource_type", ""), 36),
                str(resource.get("findings_count", 0)),
                f"{resource.get('normalized_score_percent', 0)}%",
                str(resource.get("sensitivity", "")),
            ])

        story.append(self._make_table(data, [120, 220, 55, 55, 50]))

        unassessed_resources = risk.get("unassessed_resources", [])

        if unassessed_resources:
            story.append(Spacer(1, 16))
            story.append(Paragraph("Unassessed Resources", styles["Heading2"]))
            story.append(Paragraph(
                "The following resources were discovered in the Azure Resource Group, "
                "but no specific configuration collector is currently implemented for their resource type.",
                styles["BodyText"],
            ))
            story.append(Spacer(1, 8))

            unassessed_rows = [
                ["Resource", "Type", "Reason"]
            ]

            for resource in unassessed_resources:
                unassessed_rows.append([
                    resource.get("resource_name", "-"),
                    self._shorten(resource.get("resource_type", "-"), 35),
                    resource.get("reason", "-"),
                ])

            story.append(self._make_table(unassessed_rows, [130, 150, 210]))

        return story

    @staticmethod
    def _build_styles() -> dict:
        styles = getSampleStyleSheet()

        styles.add(ParagraphStyle(
            name="TitleCustom",
            parent=styles["Title"],
            fontSize=22,
            leading=26,
            spaceAfter=18,
            alignment=TA_LEFT,
        ))

        styles.add(ParagraphStyle(
            name="Heading1Custom",
            parent=styles["Heading1"],
            fontSize=17,
            leading=21,
            spaceAfter=10,
        ))

        styles.add(ParagraphStyle(
            name="Heading2Custom",
            parent=styles["Heading2"],
            fontSize=13,
            leading=16,
            spaceBefore=8,
            spaceAfter=6,
        ))

        styles.add(ParagraphStyle(
            name="Small",
            parent=styles["Normal"],
            fontSize=9,
            leading=11,
            textColor=colors.grey,
        ))

        return styles

    @staticmethod
    def _make_table(data: list[list[Any]], col_widths: list[int]) -> Table:
        cleaned_data = []

        normal_style = ParagraphStyle(
            name="TableCell",
            fontSize=8,
            leading=10,
        )

        header_style = ParagraphStyle(
            name="TableHeader",
            fontSize=8,
            leading=10,
            textColor=colors.white,
        )

        for row_index, row in enumerate(data):
            cleaned_row = []

            for cell in row:
                text = str(cell) if cell is not None else ""
                text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

                if row_index == 0:
                    cleaned_row.append(Paragraph(text, header_style))
                else:
                    cleaned_row.append(Paragraph(text, normal_style))

            cleaned_data.append(cleaned_row)

        table = Table(cleaned_data, colWidths=col_widths, repeatRows=1)

        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1f2937")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("BACKGROUND", (0, 1), (-1, -1), colors.whitesmoke),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))

        return table

    @staticmethod
    def _make_risk_gauge(score_percent: float, grade: str) -> BytesIO | None:
        value = max(0.0, min(float(score_percent or 0.0), 100.0))
        angle = 180.0 * value / 100.0

        if value < 20:
            color = "#22c55e"
        elif value < 40:
            color = "#eab308"
        elif value < 70:
            color = "#f97316"
        else:
            color = "#ef4444"

        fig, ax = plt.subplots(figsize=(4, 2.2), subplot_kw={"aspect": "equal"})
        ax.axis("off")

        background = Wedge(
            (0, 0),
            1.0,
            180,
            0,
            facecolor="#e5e7eb",
            edgecolor="#9ca3af",
            linewidth=1,
        )

        foreground = Wedge(
            (0, 0),
            1.0,
            180,
            180 - angle,
            facecolor=color,
            edgecolor=color,
            linewidth=1,
        )

        ax.add_patch(background)
        ax.add_patch(foreground)

        ax.text(
            0,
            -0.15,
            f"{value:.1f}%",
            ha="center",
            va="center",
            fontsize=12,
            fontweight="bold",
            color="black",
        )

        ax.text(
            0,
            -0.42,
            f"{grade} risk",
            ha="center",
            va="center",
            fontsize=9,
            color="#4b5563",
        )

        ax.set_xlim(-1.1, 1.1)
        ax.set_ylim(-0.55, 1.05)

        buffer = BytesIO()
        fig.savefig(buffer, format="png", bbox_inches="tight")
        plt.close(fig)
        buffer.seek(0)

        return buffer

    @staticmethod
    def _make_severity_chart(by_severity: dict) -> BytesIO | None:
        order = ["critical", "high", "medium", "low"]
        labels = [item.capitalize() for item in order]
        values = [int(by_severity.get(item, 0)) for item in order]

        if not any(values):
            return None

        fig, ax = plt.subplots(figsize=(5, 2.6))
        ax.bar(labels, values)
        ax.set_title("Findings by severity")
        ax.set_ylabel("Count")
        plt.tight_layout()

        buffer = BytesIO()
        fig.savefig(buffer, format="png", bbox_inches="tight")
        plt.close(fig)
        buffer.seek(0)

        return buffer

    @staticmethod
    def _format_evidence(evidence: dict) -> str:
        if not evidence:
            return "-"

        if "matched_rules" in evidence:
            matched_rules = evidence.get("matched_rules", [])
            target_ports = ", ".join(evidence.get("target_ports", []))

            if not matched_rules:
                return f"No matching rule found for target ports: {target_ports}"

            parts = []

            for rule in matched_rules:
                rule_name = rule.get("name", "unknown")
                priority = rule.get("priority", "unknown")
                source = ", ".join(rule.get("source", []))
                ports = ", ".join(rule.get("matched_ports", []))

                parts.append(
                    f"NSG rule '{rule_name}' with priority {priority} allows port(s) {ports} from source {source}."
                )

            return " ".join(parts)

        if "matched_firewall_rules" in evidence:
            matched_rules = evidence.get("matched_firewall_rules", [])

            if not matched_rules:
                return "No permissive SQL firewall rule detected."

            parts = []

            for rule in matched_rules:
                rule_name = rule.get("name", "unknown")
                start_ip = rule.get("start_ip_address", "unknown")
                end_ip = rule.get("end_ip_address", "unknown")

                parts.append(
                    f"SQL firewall rule '{rule_name}' allows traffic from {start_ip} to {end_ip}."
                )

            return " ".join(parts)

        if "public_containers" in evidence:
            containers = evidence.get("public_containers", [])

            if not containers:
                return "No public containers detected."

            return "; ".join(
                f"Container '{container.get('name')}' has public access level '{container.get('public_access')}'"
                for container in containers
            )

        parts = []

        for key, value in evidence.items():
            parts.append(f"{key}: {value}")

        return "; ".join(parts)

    @staticmethod
    def _format_references(references: list[str]) -> str:
        if not references:
            return "-"

        return "\n".join(references)

    @staticmethod
    def _format_affected_resources(resources: list[dict]) -> str:
        if not resources:
            return "-"

        names = [
            resource.get("name", "")
            for resource in resources
            if resource.get("name")
        ]

        return ", ".join(names) if names else "-"

    @staticmethod
    def _shorten(value: str, max_len: int) -> str:
        if not value:
            return ""

        if len(value) <= max_len:
            return value

        return value[: max_len - 3] + "..."